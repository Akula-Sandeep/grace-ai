SELECT format('CREATE ROLE grace_app LOGIN PASSWORD %L', :'APP_DB_PASSWORD')
WHERE NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'grace_app')\gexec
ALTER ROLE grace_app PASSWORD :'APP_DB_PASSWORD';

SELECT format('CREATE ROLE grace_migrator LOGIN PASSWORD %L', :'MIGRATOR_DB_PASSWORD')
WHERE NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'grace_migrator')\gexec
ALTER ROLE grace_migrator PASSWORD :'MIGRATOR_DB_PASSWORD';

GRANT CONNECT ON DATABASE :"POSTGRES_DB" TO grace_app;
GRANT CONNECT, TEMPORARY ON DATABASE :"POSTGRES_DB" TO grace_migrator;
GRANT USAGE ON SCHEMA public TO grace_app;
GRANT USAGE, CREATE ON SCHEMA public TO grace_migrator;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO grace_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO grace_app;
ALTER DEFAULT PRIVILEGES FOR ROLE grace_migrator IN SCHEMA public
  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO grace_app;
ALTER DEFAULT PRIVILEGES FOR ROLE grace_migrator IN SCHEMA public
  GRANT USAGE, SELECT ON SEQUENCES TO grace_app;
